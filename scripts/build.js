#!/usr/bin/env node
// Builds unpacked extensions for each browser into dist/<target> and the
// userscript into userscript/ (committed, so script managers can auto-update
// from GitHub).
// Usage: node scripts/build.js [chrome|firefox|safari|userscript ...] [--zip]
const fs = require('fs');
const path = require('path');
const { execFileSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'src');
const DIST = path.join(ROOT, 'dist');
const REPO = 'cybertatar/YouTubeMusicTimecodePlugin';
const USERSCRIPT = path.join(ROOT, 'userscript', 'ytm-timecodes.user.js');
const USERSCRIPT_URL = `https://raw.githubusercontent.com/${REPO}/main/userscript/ytm-timecodes.user.js`;
// Order matters: libraries first, the bridge before the UI that talks to it.
const USERSCRIPT_SOURCES = ['lib/timecodes.js', 'lib/innertube.js', 'page/bridge.js', 'content/content.js'];

const TARGETS = {
  chrome: (m) => m,
  firefox: (m) => ({
    ...m,
    browser_specific_settings: {
      gecko: {
        id: 'ytm-timecodes@cybertatar',
        strict_min_version: '121.0',
        data_collection_permissions: { required: ['none'] },
      },
    },
  }),
  safari: (m) => m,
};

function readJson(file) {
  return JSON.parse(fs.readFileSync(file, 'utf8'));
}

// _locales/<lang>/messages.json -> {key: 'text with $1 placeholders'}
function flatMessages(lang) {
  const out = {};
  for (const [key, { message, placeholders }] of Object.entries(readJson(path.join(SRC, '_locales', lang, 'messages.json')))) {
    out[key] = message.replace(/\$(\w+)\$/g, (m, name) => {
      const p = placeholders && placeholders[name.toLowerCase()];
      return p ? p.content : m;
    });
  }
  return out;
}

function generateUserscript() {
  const manifest = readJson(path.join(SRC, 'manifest.json'));
  const en = flatMessages('en');
  const ru = flatMessages('ru');
  const header = [
    '// ==UserScript==',
    `// @name         ${en.extName}`,
    `// @name:ru      ${ru.extName}`,
    `// @namespace    https://github.com/${REPO}`,
    `// @version      ${manifest.version}`,
    `// @description  ${en.extDescription}`,
    `// @description:ru ${ru.extDescription}`,
    '// @author       cybertatar',
    `// @homepageURL  https://github.com/${REPO}`,
    `// @supportURL   https://github.com/${REPO}/issues`,
    `// @icon         https://raw.githubusercontent.com/${REPO}/main/src/icons/icon128.png`,
    `// @updateURL    ${USERSCRIPT_URL}`,
    `// @downloadURL  ${USERSCRIPT_URL}`,
    '// @match        https://music.youtube.com/*',
    '// @grant        none',
    '// @inject-into  auto',
    '// @run-at       document-idle',
    '// @noframes',
    '// ==/UserScript==',
    '',
    '// Generated by scripts/build.js from src/ — edit the sources, not this file.',
    '',
  ].join('\n');
  const messages =
    `globalThis.YTMTC = Object.assign(globalThis.YTMTC || {}, {\n` +
    `  messages: /^ru\\b/i.test(navigator.language) ? ${JSON.stringify(ru)} : ${JSON.stringify(en)},\n` +
    `});\n`;
  const body = USERSCRIPT_SOURCES.map((f) => `// ---- ${f}\n` + fs.readFileSync(path.join(SRC, f), 'utf8'));
  return header + '\n' + [messages, ...body].join('\n');
}

function buildExtension(target, zip) {
  const out = path.join(DIST, target);
  fs.rmSync(out, { recursive: true, force: true });
  fs.cpSync(SRC, out, { recursive: true });

  const manifest = readJson(path.join(SRC, 'manifest.json'));
  fs.writeFileSync(path.join(out, 'manifest.json'), JSON.stringify(TARGETS[target](manifest), null, 2) + '\n');

  if (zip && target !== 'safari') {
    const file = path.join(DIST, `ytm-timecodes-${target}-${manifest.version}.zip`);
    fs.rmSync(file, { force: true });
    execFileSync('zip', ['-qr', file, '.'], { cwd: out });
    console.log(`Packed ${path.relative(ROOT, file)}`);
  }
  console.log(`Built dist/${target}`);
}

function buildUserscript() {
  fs.mkdirSync(path.dirname(USERSCRIPT), { recursive: true });
  fs.writeFileSync(USERSCRIPT, generateUserscript());
  console.log(`Built ${path.relative(ROOT, USERSCRIPT)}`);
}

if (require.main === module) {
  const args = process.argv.slice(2);
  const zip = args.includes('--zip');
  const targets = args.filter((a) => !a.startsWith('--'));
  for (const target of targets.length ? targets : [...Object.keys(TARGETS), 'userscript']) {
    if (target === 'userscript') buildUserscript();
    else if (TARGETS[target]) buildExtension(target, zip);
    else throw new Error(`Unknown target: ${target}`);
  }
}

module.exports = { generateUserscript, USERSCRIPT };
